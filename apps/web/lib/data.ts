function normalizeTicker(ticker: string): string {
  return ticker.trim().toUpperCase();
}

function unavailableFixture<T>(ticker: string): Result<T> {
  const normalizedTicker = normalizeTicker(ticker);
  return refusal(
    "unknown-ticker",
    `${normalizedTicker || "That ticker"} is not present in the committed preview fixture. Try AAPL.`,
  );
}

function success<T>(data: T): Result<T> {
  return { ok: true, data };
}

function refusal<T>(reason: RefusalReason, message: string): Result<T> {
  return { ok: false, refusal: { reason, message } };
}

function isVerbatimSignal(signal: Signal): boolean {
  const sourceSection = sections.find(
    (section) => section.id === signal.locator.sectionId,
  );
  if (!sourceSection) {
    return false;
  }

  const { offset } = signal.locator;
  return sourceSection.text.slice(offset, offset + signal.quote.length) === signal.quote;
}

/**
 * Fixture seam for deterministic figures. The snapshot was produced by core
 * from committed XBRL facts; issue #5 replaces it with the live core call.
 */
export async function getRatios(ticker: string): Promise<Result<RatiosData>> {
  if (normalizeTicker(ticker) !== company.ticker) {
    return unavailableFixture(ticker);
  }

  return success({ company, filing, ratios: aaplRatios });
}

/**
 * Fixture seam for grounded prose. The pause makes the required Suspense phase
 * visible in preview; live extraction replaces it in issue #5.
 */
export async function getSignals(ticker: string): Promise<Result<SignalsData>> {
  if (normalizeTicker(ticker) !== company.ticker) {
    return unavailableFixture(ticker);
  }

  if (process.env.NODE_ENV !== "test") {
    await new Promise<void>((resolve) => setTimeout(resolve, 1_200));
  }

  const signals = signalFixture.filter(isVerbatimSignal);
  if (signals.length === 0) {
    return refusal(
      "section-not-found",
      "No grounded signal in the preview fixture could be traced to an exact filing span.",
    );
  }

  return success({ filing, sections, signals });
}
