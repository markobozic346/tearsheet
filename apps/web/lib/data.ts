export type RatiosData = Pick<Tearsheet, "company" | "filing" | "ratios">;
export type SignalsData = Pick<Tearsheet, "filing" | "sections" | "signals">;

const company: Company = rawFiling.company;
const filing: FilingRef = rawFiling.filing;

function isSectionId(value: string): value is SectionId {
  return value === "risk-factors" || value === "mdna";
}

const sections: Section[] = rawFiling.sections.flatMap((section) => {
  if (!isSectionId(section.id)) {
    return [];
  }

  return [{ ...section, id: section.id }];
});

